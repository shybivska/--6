package com.deposits.model;
import java.util.ArrayList;
import java.util.List;

/**
 * Клас-контейнер (Catalog).
 * Його головна задача — зберігати у оперативній пам'яті список усіх
 * доступних банківських вкладів, які були завантажені з файлу.
 * Сервіс пошуку звертається саме сюди, щоб отримати дані для аналізу.
 */
public class KatalogVkladiv {

    /**
     * Внутрішній список, де фізично зберігаються об'єкти Vklad.
     * Ми використовуємо ArrayList, бо це зручний динамічний масив.
     */
    private List<Vklad> vklady = new ArrayList<>();

    /**
     * Метод для додавання одного вкладу в каталог.
     * Використовується класом JsonSkhovyshche під час зчитування файлу:
     * прочитав один об'єкт -> додав його сюди.
     *
     * @param v Об'єкт вкладу, який треба зберегти.
     */
    public void dodatyVklad(Vklad v) {
        vklady.add(v);
    }

    /**
     * Метод для отримання всього списку.
     * Використовується класом ServisPidboru, коли йому треба перебрати
     * всі вклади, щоб знайти потрібний клієнту.
     *
     * @return Список всіх вкладів.
     */
    public List<Vklad> otrymatyVsiVklady() {
        return vklady;
    }
}