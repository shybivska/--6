package com.deposits.model;

/**
 * Клас-модель для Ощадного Вкладу.
 * Цей тип вкладу призначений насамперед для накопичення коштів ("Скарбничка").
 * Його головна ідея — людина регулярно відкладає гроші (поповнює),
 * але не обов'язково має право їх вільно знімати.
 */
public class OschadnyVklad extends Vklad {

    /**
     * Чи дозволено поповнювати цей вклад?
     * @return true - ЗАВЖДИ ТАК. Це фундаментальна суть ощадного рахунку:
     * клієнт повинен мати змогу докладати гроші, щоб назбирати потрібну суму.
     */
    @Override
    public boolean chyMozhnaPopovnyuvaty() {
        return true;
    }

    /**
     * Чи дозволено знімати гроші достроково?
     * Ощадні вклади бувають різні:
     * деякі ("Скарбничка") дозволяють зняття, інші (накопичувальні на строк) — ні.
     * * Тому ми не пишемо тут жорстко true чи false, а повертаємо значення змінної
     * 'mozhnaZnyatyDostrokovo', яка була завантажена з файлу deposits.json
     * для конкретного банку.
     */
    @Override
    public boolean chyMozhnaZnyatyDostrokovo() {
        return mozhnaZnyatyDostrokovo;
    }
}